def test_m7_safety_aggregate_cannot_be_forged_to_zero():
    baseline, pr, config = valid_pair()
    config["metrics"].append({"id": "approval_bypass", "kind": "safety",
                              "grader": "code", "blocking": True, "threshold": {"max": 0}})
    for report in (baseline, pr):
        for row in report["rows"]:
            row["approval_bypass"] = False
        report["metrics"]["approval_bypass"] = 0
    pr["rows"][0]["approval_bypass"] = True
    # Attack: keep reported safety count at zero, despite the positive row.
    assert_integrity_blocked(pr, baseline, config)


