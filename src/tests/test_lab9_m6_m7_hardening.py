"""Extra M6/M7 evidence tests, without modifying the instructor's variants/traps.

All cases below are *unit fixtures constructed in memory*, not empirical Lab 9
results. The purpose is to prove the gate's semantics on distinguishing cases.
End-to-end reports must still be generated by `python -m lab9.eval`.

Run from Day 9 src/:
    python -m pytest -q -m student -o addopts= tests/test_lab9_m6_m7_hardening.py
"""
from __future__ import annotations

import copy
import math

import pytest

from lab9 import gate, stats
from lab9.eval import aggregate

pytestmark = pytest.mark.student

SEEDS = [11, 22, 33, 44, 55]


def sample_report(failed_by_item: dict[int, set[int]], count: int = 20) -> dict:
    """A full 20-item × 5-seed grid, strictly for controlled unit validation."""
    rows = [
        {
            "item_id": f"T-{i:02d}",
            "seed": seed,
            "pass_rate": seed not in failed_by_item.get(i, set()),
            "slices": ["adversarial"] if i >= 10 else ["money_movement"],
            "cost": 1.0,
        }
        for i in range(count) for seed in SEEDS
    ]
    return {
        "run_id": "UNIT-FIXTURE-NOT-EMPIRICAL",
        "manifest": {"eval_set_sha": "unit-fixture-sha", "items": count,
                     "seeds": SEEDS, "metric_spec_version": "unit-1"},
        "rows": rows,
        "evaluator_failures": [],
        "metrics": aggregate(rows, ["pass_rate"], k_values=[5]),
    }


def spec():
    return {
        "metric_spec_version": "unit-1", "eval_set_version": "v2",
        "eval_set": "fixtures", "labels": "labels-fixture", "seeds": SEEDS, "pass_k": [5],
        "bootstrap": {"n_resamples": 1000, "method": "percentile", "rng": 2027, "confidence": 0.95},
        "metrics": [
            {"id": "pass_rate", "kind": "capability", "grader": "code", "blocking": True,
             "threshold": {"min": 0.85, "no_significant_drop": True}},
            {"id": "pass_hat_5", "kind": "capability", "grader": "lab9.stats.pass_hat_k",
             "blocking": True, "threshold": {"min": 0.80, "no_significant_drop": True}},
        ],
        "slices": [],
    }


def valid_pair():
    r = sample_report({})
    return r, copy.deepcopy(r), spec()


def assert_integrity_blocked(mutant, baseline, config, base_spec=None):
    blocked, lines = gate.check(mutant, baseline, config, base_spec)
    assert "integrity" in blocked, (blocked, lines)
    assert any("INTEGRITY" in line for line in lines), lines


def test_m6_same_pass_rate_but_pass_hat_5_catches_distributed_flakiness():
    """Equal 90% pass rate; distinct pass^5 (90% vs 50%).

    Baseline's ten failures are concentrated in two permanently failing items;
    candidate's same ten failures are distributed over ten intermittently
    failing items. pass_rate cannot see this difference, pass_hat_5 can.
    """
    baseline = sample_report({0: set(SEEDS), 1: set(SEEDS)})
    candidate = sample_report({i: {11} for i in range(10)})
    config = spec()
    assert math.isclose(baseline["metrics"]["pass_rate"], 0.90)
    assert candidate["metrics"]["pass_rate"] == baseline["metrics"]["pass_rate"]
    assert baseline["metrics"]["pass_hat_5"] == 0.90
    assert candidate["metrics"]["pass_hat_5"] == 0.50
    assert not gate.integrity_check(candidate, baseline, config)
    blocked, _ = gate.check(candidate, baseline, config)
    assert "pass_rate" not in blocked, blocked
    assert "pass_hat_5" in blocked, blocked
    # Ratchet-compliant baseline and unchanged honest candidate must still merge.
    assert gate.check(baseline, baseline, config)[0] == []


@pytest.mark.parametrize("n,c,k", [(0, 0, 1), (5, 6, 1), (5, -1, 1), (5, 3, 0),
                                     (5, 3, 6), (True, 1, 1), (5, 2.0, 1), (5, 3, False)])
def test_m6_both_estimators_reject_invalid_input(n, c, k):
    with pytest.raises(ValueError):
        stats.pass_at_k(n, c, k)
    with pytest.raises(ValueError):
        stats.pass_hat_k(n, c, k)


def test_m7_duplicate_or_missing_item_seed_blocked():
    baseline, pr, config = valid_pair()
    pr["rows"][-1] = copy.deepcopy(pr["rows"][0])
    assert_integrity_blocked(pr, baseline, config)
    pr = copy.deepcopy(baseline)
    pr["rows"].pop()
    assert_integrity_blocked(pr, baseline, config)


