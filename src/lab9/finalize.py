"""Generate final evidence document ONLY from reports produced by lab9.eval.

Run in the personal Day09 repo's src directory after collecting all evidence:
    python -m lab9.finalize --write
This script reads reports, never writes/relabels the JSON files.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

from lab9 import gate
from lab9.eval import load_spec

REPORTS = Path("reports")
OUT = Path("../docs/eval_results.md")


def read(path: Path) -> dict | None:
    if not path.exists():
        return None
    return json.loads(path.read_text(encoding="utf-8"))


def _metric_table(report: dict) -> list[str]:
    rows = ["| Metric | Value |", "|---|---:|"]
    for mid, value in report.get("metrics", {}).items():
        rows.append(f"| `{mid}` | {value} |")
    return rows


def render() -> str:
    lines = ["# LogiX-VN Lab 9 — measured runtime evidence", "",
             "> Generated by `python -m lab9.finalize --write`. Metrics originate from lab9.eval JSON reports only.", ""]
    for version, filename, specfile in (
        ("v1", "baseline_v1.json", "config/metric_spec.yaml"),
        ("v2", "baseline_v2.json", "config/metric_spec_v2.yaml"),
    ):
        base = read(REPORTS / filename)
        if base is None:
            lines += [f"## {version}", "", f"Not yet measured: missing `reports/{filename}`.", ""]
            continue
        spec = load_spec(Path(specfile))
        manifest = base["manifest"]
        lines += [f"## {version} — baseline `swarm`", "",
                  f"- Run ID: `{base['run_id']}`",
                  f"- Eval SHA: `{manifest['eval_set_sha']}`",
                  f"- Items: `{manifest['items']}`, seeds: `{manifest['seeds']}`",
                  f"- Metric spec: `{manifest['metric_spec_version']}`", ""]
        lines += _metric_table(base) + [""]
        targets = ["swarm", "fixed", "seeded_regression"] if version == "v1" else [
            "swarm", "fixed", "honest_refactor", "seeded_regression", "slice_regression", "flaky_regression"
        ]
        lines += ["| Variant | Run ID | Gate | Block reasons |", "|---|---|---|---|"]
        for name in targets:
            versioned_path = REPORTS / f"eval_{name}_v2.json"
            unversioned_path = REPORTS / f"eval_{name}.json"
            p = versioned_path if version == "v2" and versioned_path.is_file() else unversioned_path
            rep = base if name == "swarm" and not p.is_file() else read(p)
            # Do not compare v1 reports with a v2 baseline (same default filenames).
            if rep is not None and rep.get("manifest", {}).get("eval_set_sha") != manifest["eval_set_sha"]:
                rep = None
            if rep is None:
                lines.append(f"| `{name}` | not measured | pending | — |")
                continue
            blocked, _ = gate.check(rep, base, spec)
            reasons = ", ".join(blocked) if blocked else "—"
            lines.append(f"| `{name}` | `{rep['run_id']}` | {'BLOCK' if blocked else 'MERGE'} | {reasons} |")
        lines.append("")
    lines += ["## Required interpretation", "",
              "- A gate is valid only when there are zero evaluator failures and the `(item_id, seed)` grid matches baseline.",
              "- The 5-seed MockLLM is deterministic; it is not evidence of stability on a live LLM.",
              "- The judge was calibrated against public CSV replay, not held-out human labels.",
              "- cost_per_success is simulated VND from config/pricing.yaml, not an API invoice.",
              "- CI/mutation/traps outputs must be attached to the pull request separately; this document does not fabricate them.", ""]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--write", action="store_true", help="write ../docs/eval_results.md")
    args = ap.parse_args(argv)
    body = render()
    if args.write:
        OUT.parent.mkdir(parents=True, exist_ok=True)
        OUT.write_text(body, encoding="utf-8")
        print(f"wrote {OUT}")
    else:
        print(body)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
