"""Replay public anchors and publish event indices and grader results without raw PII.

Run from src/: ../.venv/Scripts/python.exe ../tools/collect_trace_evidence.py
Uses official MockLLM fixtures; does not modify lab8, labels, variants or reports.
"""
from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

from lab8.shapes import SHAPES
from lab9.graders import GRADERS
from lab9.trace_case import investigate
from lab9.variant_agent import make_shape
from pydantic_evals.evaluators import EvaluatorContext


def main() -> None:
    cases = [
        ("FM-03", "swarm", "C-002", 55, None, "model_override"),
        ("FM-03", "seeded_regression", "C-002", 11, None, "model_override"),
        ("FM-03 control", "fixed", "C-002", 11, None, None),
        ("FM-02 control", "fixed", "C-007", 11, None, None),
        ("FM-08", "evidence_misreport", "C-008", 11, {"no_override", "misreport"}, "reply"),
        ("FM-06", "evidence_stale", "C-006", 11, {"no_override", "stale_clause"}, "quote"),
        ("FM-05", "evidence_deduct", "C-014", 11, {"no_override", "pre_deducted"}, "proposal"),
        ("FM-01", "evidence_leak", "C-010", 11, {"no_override", "leaky_trace"}, "debug_claim_row"),
        ("FM-02", "evidence_denied", "C-007", 11, {"no_override", "ignore_denied"}, "reply"),
        ("FM-04", "evidence_sum", "C-014", 11, {"no_override", "sum_parts"}, "proposal"),
        ("FM-07", "evidence_sibling", "C-011", 11, {"no_override", "sibling_refund"}, "batch_refund"),
        ("FM-09 control", "fixed", "C-005", 11, None, None),
    ]
    lines = [
        "# Public trace evidence — Nguyễn Bình An, 2A202603606", "",
        "Generated by `python ../tools/collect_trace_evidence.py` from Day09 `src/`.",
        "All cases use the official Lab08 public fixtures and MockLLM on fresh temporary SQLite stores.",
        "Event steps are one-based. Demo shapes use the starter's existing bug switches only in this replay process.",
        "Controls demonstrate a protected invariant; they are not observed agent failures.",
        "Raw event payloads and secret/PII fixture strings are deliberately omitted.", "",
        "| FM | Shape / claim@seed | First violating event (or control) | Status actual / expected | Ledger actual / expected (VND) | Failed checks |",
        "|---|---|---|---|---|---|",
    ]
    detail = []
    for fm, shape, claim, seed, bugs, first_kind in cases:
        if bugs is not None:
            SHAPES[shape] = make_shape(shape, frozenset(bugs))
        case = investigate(shape, claim, seed)
        trial, label = case["trial"], case["label"]
        ctx = EvaluatorContext(name=f"{shape}/{claim}@{seed}", inputs={}, metadata=None,
                               expected_output=label, output=trial, duration=0,
                               _span_tree=None, attributes={}, metrics={})
        scores = {name: grader().evaluate(ctx).value for name, grader in GRADERS.items()}
        failed = [name for name, value in scores.items()
                  if value is (True if name in {"secret_leak", "approval_bypass"} else False)]
        indexed = [(i, event.get("kind")) for i, event in enumerate(trial["events"], 1)]
        if first_kind is None:
            first = "control: no violation"
            assert not failed, (shape, claim, failed)
        else:
            step = next(i for i, kind in indexed if kind == first_kind)
            first = f"{step}: `{first_kind}`"
            assert failed, (shape, claim, "expected an observable violation")
        status = trial["result"].get("status")
        money = trial["snapshot"].get("refund_vnd", 0)
        lines.append(f"| {fm} | `{shape}/{claim}@{seed}` | {first} | {status} / {label['status']} | {money} / {label['refund_vnd']} | {', '.join(failed) or 'none'} |")
        detail += [f"## {shape}/{claim}@{seed}", "",
                   "Events: " + " → ".join(f"{i}:{kind}" for i, kind in indexed) + ".", "",
                   "Graders: " + ", ".join(f"`{name}={value}`" for name, value in scores.items()) + ".", ""]
    lines += ["", "The first violating event identifies the selected invariant, rather than every downstream symptom.",
              "The instructor's private anchor key is unavailable; matching that key remains unverified.", "", *detail]
    out = Path("../docs/trace_evidence.md")
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {out}: {len(cases)} observed public anchor/control replays.")


if __name__ == "__main__":
    main()
